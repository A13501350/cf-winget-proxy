// ─── Main handler ─────────────────────────────────────────────────────────────

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url);
    const { pathname } = url;
    const mirror = (env.MIRROR || "https://gh-proxy.org").replace(/\/+$/, "");

    // Landing page
    if (pathname === "/" || pathname === "") {
      return landingPage(url.host, mirror);
    }

    // ── Microsoft.Rest API endpoints ────────────────────────────────────────
    // Operational read-out for "is the search broken because the index is
    // missing?" — which otherwise looks identical to "nothing matches that
    // keyword". Fetches with force, so it reports the origin rather than a memo
    // a previous request happened to leave behind.
    if (pathname === "/_index" && request.method === "GET") {
      const index = await getIndex(env, { force: true });
      return Response.json({
        url: env.INDEX_URL ?? null,
        entries: index?.length ?? 0,
        first: index?.[0]?.id ?? null,
        withMoniker: index?.filter((e) => e.m).length ?? 0,
        withTags: index?.filter((e) => e.t).length ?? 0,
      });
    }

    if (pathname === "/information" && request.method === "GET") {
      return handleInformation();
    }
    if (pathname === "/manifestSearch" && request.method === "POST") {
      return handleManifestSearch(request, env);
    }
    // /packageManifests/{id}  or  /packageManifests/{id}/{version}
    const mfMatch = pathname.match(
      /^\/packageManifests\/([^/]+)(?:\/([^/]+))?$/
    );
    if (mfMatch && request.method === "GET") {
      const id = decodeURIComponent(mfMatch[1]);
      // winget passes the version as a query param (?Version=...), not a path
      // segment; honor it so we fetch the exact requested version directly
      // instead of falling back to a rate-limited GitHub API version listing.
      const version =
        (mfMatch[2]
          ? decodeURIComponent(mfMatch[2])
          : url.searchParams.get("Version")) ?? null;
      return handlePackageManifest(id, version, mirror, env);
    }

    // ── This worker is manifest-only. Installer downloads are rewritten to the
    //    mirror (ghproxy) inside handlePackageManifest, so the client fetches
    //    them directly from the mirror. No download-proxy branch is needed. ──
    return new Response("Not found", { status: 404 });
  },
};
